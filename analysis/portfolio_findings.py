"""Render docs/portfolio_findings.md from the CSVs written by analysis/portfolio.py.

Every number in the document is read from analysis/output/portfolio_*.csv; the prose only
chooses words (higher/lower, rises/falls) by comparing those numbers. Re-run after
`make portfolio` and the document follows the data.

Usage:
    .venv/bin/python analysis/portfolio_findings.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def num(x: float) -> str:
    return f"{int(round(x)):,}"


class Outputs:
    """The portfolio CSVs, with small lookup helpers."""

    def __init__(self, out: Path):
        self.health = pd.read_csv(out / "portfolio_health.csv")
        self.power = pd.read_csv(out / "portfolio_power.csv")
        self.inf = pd.read_csv(out / "portfolio_inference.csv")
        self.win = pd.read_csv(out / "portfolio_winners.csv")
        self.hist = pd.read_csv(out / "portfolio_pvalues.csv")

    def h(self, metric: str, window: str) -> pd.Series:
        r = self.health[(self.health["metric"] == metric) & (self.health["window"] == window)]
        return r.iloc[0]

    def i(self, metric: str, sample: str = "clean") -> float:
        r = self.inf[(self.inf["sample"] == sample) & (self.inf["metric"] == metric)]
        return float(r["value"].iloc[0])

    def p(self, lift: float, correction: str = "bonferroni_k_minus_1") -> pd.Series:
        r = self.power[
            (self.power["correction"] == correction) & (self.power["target_lift"] == lift)
        ]
        return r.iloc[0]

    def w(self, dim: str) -> pd.DataFrame:
        return self.win[self.win["dimension"] == dim]


def _rate(r: pd.Series) -> str:
    return f"{pct(r['share'])} ({num(r['k'])} of {num(r['n'])})"


def _rate_ci(r: pd.Series) -> str:
    return (
        f"{pct(r['share'])} ({num(r['k'])} of {num(r['n'])}; "
        f"95% CI {pct(r['ci_low'])} to {pct(r['ci_high'])})"
    )


def _share_of(r: pd.Series, what: str) -> str:
    if r["n_powered"] == 0:
        return f"None of the {num(r['n_tests'])} clean tests could detect {what}"
    return f"{pct(r['share_powered'])} of clean tests could detect {what}"


def _table(df: pd.DataFrame, label: str) -> list[str]:
    lines = [
        f"| {label} | clean tests | declared winners | survive Holm | survive BH | survive both |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in df.itertuples():
        lines.append(
            f"| {r.level} | {num(r.n_tests)} | {num(r.n_with_winner)} | "
            f"{pct(r.share_survive_within)} | {pct(r.share_survive_portfolio)} | "
            f"{pct(r.share_survive_both)} |"
        )
    return lines


def render(o: Outputs) -> str:
    srm_in, srm_out = o.h("srm_fail", "inside"), o.h("srm_fail", "outside")
    srm_all = o.h("srm_fail", "all")
    flagged = o.h("flagged", "all")
    aa_in, aa_out = o.h("aa_p05_all_pairs", "inside"), o.h("aa_p05_all_pairs", "outside")
    aa1_out = o.h("aa_p05_first_pair_per_test", "outside")
    aas_out = o.h("aa_p05_strict_pairs", "outside")
    aa_clean = o.h("aa_p05_all_pairs_clean_tests", "outside")
    aa_ratio = aa_clean["share"] / aa_clean["expected_share"]

    n_clean = o.i("n_tests")
    p5, p10, p20 = o.p(0.05), o.p(0.10), o.p(0.20)
    u20 = o.p(0.20, "none")
    pi0 = o.i("pi0")
    raw, bh = o.i("n_raw_significant"), o.i("n_bh_significant")
    pi0_lo, pi0_hi = o.i("pi0_lambda_0.8"), o.i("pi0_lambda_0.2")
    flat = o.hist[o.hist["bin_low"] >= 0.5]["n_tests"].mean()
    first_bin = o.hist.iloc[0]["n_tests"]

    w = o.w("all").iloc[0]
    years = o.w("year")
    y0, y1 = years.iloc[0], years.iloc[-1]
    sizes = o.w("size")
    s0, s1 = sizes.iloc[0], sizes.iloc[-1]
    arms = o.w("arms")
    a0, a1 = arms.iloc[0], arms.iloc[-1]

    lines = [
        "# How many of Upworthy's A/B test results hold up?",
        "",
        "<!-- Generated by analysis/portfolio_findings.py from analysis/output/portfolio_*.csv."
        " Do not edit by hand; run `make portfolio findings`. -->",
        "",
        "A portfolio view of the Upworthy Research Archive: every test run through the `abtest` "
        "library by `analysis/portfolio.py`. Tests inside the 2013-06-25..2014-01-10 "
        f"randomization-risk window or failing SRM are flagged ({num(flagged['k'])} of "
        f"{num(flagged['n'])}) and left out of everything after section 1, leaving "
        f"**{num(n_clean)} clean tests**.",
        "",
        "## Headline numbers",
        "",
        f"1. **Randomization broke inside the risk window.** SRM fails in {_rate(srm_in)} of "
        f"tests inside it vs {_rate(srm_out)} outside. A/A pairs reach p < 0.05 in "
        f"{pct(aa_in['share'])} of cases inside and {pct(aa_out['share'])} outside, against "
        "5% expected.",
        f"2. **Almost no test was powered for a realistic lift.** "
        f"{_share_of(p10, 'a 10% lift at 80% power')}; the median minimum detectable "
        f"lift is {pct(p10['mde_median'], 0)}.",
        f"3. **Storey's pi0 = {pi0:.2f}**: taken at face value, about "
        f"{pct(1 - pi0, 0)} of clean tests have some real difference between arms (but see "
        "the A/A caveat below).",
        f"4. **{num(raw)} of {num(n_clean)} clean tests are significant at p < 0.05 raw; "
        f"{num(bh)} after Benjamini-Hochberg at 5%.**",
        f"5. **Only {pct(w['share_survive_both'])} of {num(w['n_with_winner'])} declared "
        "winners survive both Holm within their test and BH across tests** "
        f"({pct(w['share_survive_within'])} survive Holm, {pct(w['share_survive_portfolio'])} "
        "survive BH).",
        "",
        "## 1. Data health",
        "",
        "![SRM and A/A rates inside vs outside the risk window]"
        "(../analysis/output/portfolio_health.png)",
        "",
        f"**SRM.** {_rate(srm_all)} of tests fail a chi-square test of an equal split at "
        f"p < 0.001. Inside the risk window it is {_rate_ci(srm_in)}; outside, "
        f"{_rate_ci(srm_out)}, against {pct(srm_out['expected_share'])} expected "
        "by chance. The window is where traffic allocation broke, and outside it SRM is rare.",
        "",
        f"**A/A pairs.** Arms with the same headline and image should differ at p < 0.05 about "
        f"5% of the time. Across {num(aa_out['n'])} pairs outside the window the rate is "
        f"{_rate_ci(aa_out)}; inside it is {pct(aa_in['share'])}. Taking "
        f"one pair per test, so no arm counts twice, gives {pct(aa1_out['share'])} outside; "
        f"pairs that also share excerpt and lede give {pct(aas_out['share'])}. "
        f"Restricted to clean tests the rate is still {pct(aa_clean['share'])}, "
        f"{aa_ratio:.1f} times the nominal 5%.",
        "",
        "Unlike SRM, the A/A excess is not confined to the risk window, so dropping flagged "
        'tests does not remove it. Either the "identical" arms differed in something the '
        "archive does not record, or click counts vary more than a binomial model allows "
        "(for example traffic that changes over the life of a test). Either way, a pooled z-test "
        "or chi-square p-value on this data is too small for a true null, and that matters for "
        "sections 3 and 4.",
        "",
        "## 2. Power",
        "",
        "![Distribution of minimum detectable lift](../analysis/output/portfolio_mde.png)",
        "",
        "For each clean test, the smallest relative lift detectable at 80% power, at the "
        "test's pooled click rate and mean impressions per arm, with alpha split over the "
        "k - 1 comparisons:",
        "",
        "| target lift | tests powered | share |",
        "|---:|---:|---:|",
    ]
    for r in (p5, p10, p20):
        lines.append(
            f"| {pct(r['target_lift'], 0)} | {num(r['n_powered'])} of {num(r['n_tests'])} | "
            f"{pct(r['share_powered'])} |"
        )
    lines += [
        "",
        f"The median MDE is {pct(p10['mde_median'], 0)} (middle half {pct(p10['mde_p25'], 0)} "
        f"to {pct(p10['mde_p75'], 0)}). Even without splitting alpha across arms, "
        f"{pct(u20['share_powered'], 2)} of tests are powered for a 20% lift and the median "
        f"MDE is {pct(u20['mde_median'], 0)}. A typical test could reliably detect only a lift "
        f"of about {pct(p10['mde_median'], 0)}. When a test this small does reach "
        "significance, the estimated lift is usually inflated (the winner's curse; "
        "`analysis/shrinkage.py` measures how much).",
        "",
        "## 3. Portfolio inference",
        "",
        "![Distribution of omnibus p-values](../analysis/output/portfolio_pvalues.png)",
        "",
        f"One chi-square omnibus p-value per clean test. {num(first_bin)} fall below 0.05, "
        f"against an average of {num(flat)} per 0.05-wide bin above 0.5. Storey's estimate of "
        f"the share of tests with no real difference is pi0 = {pi0:.2f} at lambda = 0.5, "
        f"ranging from {pi0_hi:.2f} (lambda = 0.2) to {pi0_lo:.2f} (lambda = 0.8).",
        "",
        f"At face value: {num(raw)} tests ({pct(raw / n_clean)}) are significant raw and "
        f"{num(bh)} ({pct(bh / n_clean)}) after BH at 5%, and with pi0 = {pi0:.2f} BH's "
        f"actual FDR bound is {pct(o.i('bh_fdr_bound'))}.",
        "",
        f"**Caveat.** pi0 and BH both assume a null p-value is uniform. The A/A pairs show it "
        f"is not here: identical arms reach p < 0.05 {aa_ratio:.1f} times as often as they "
        "should. Null tests therefore pile up near 0 too, which pushes pi0 down and the BH "
        f"count up. Read {pi0:.2f} as a lower bound on the share of null tests and {num(bh)} "
        "as an upper bound on the discoveries.",
        "",
        "## 4. Upworthy's declared winners",
        "",
        "![Winner survival by year and test size](../analysis/output/portfolio_winners.png)",
        "",
        f"{num(w['n_with_winner'])} clean tests have a declared winner. Inside a test there is "
        "no control arm, so the winner is compared with every other arm and survives Holm only "
        "if it has the higher click rate in all comparisons and all are rejected. "
        f"{pct(w['share_survive_within'])} survive. In {num(w['n_winner_not_top_ctr'])} tests "
        f"({pct(w['n_winner_not_top_ctr'] / w['n_with_winner'])}) the declared winner does "
        "not even have the highest observed click rate. Across tests, "
        f"{pct(w['share_survive_portfolio'])} of winners sit in a test whose omnibus p-value "
        f"survives BH, and {pct(w['share_survive_both'])} pass both.",
        "",
        f"Holm within the test is the binding filter: {num(w['n_survive_both'])} of the "
        f"{num(w['n_survive_within'])} winners that survive Holm also survive BH. The same A/A "
        "caveat applies, since Holm uses the same kind of p-values, so "
        f"{pct(w['share_survive_both'])} is an upper bound on the share of winners that "
        "would hold up.",
        "",
        "**By year.** Survival of both corrections "
        f"{'falls' if y1['share_survive_both'] < y0['share_survive_both'] else 'rises'} from "
        f"{pct(y0['share_survive_both'])} in {y0['level']} to {pct(y1['share_survive_both'])} "
        f"in {y1['level']}, while the share of tests with a declared winner goes from "
        f"{pct(y0['share_with_winner'])} to {pct(y1['share_with_winner'])}. Clean 2013 tests "
        "all start before the risk window opens on 2013-06-25.",
        "",
        *_table(years, "year"),
        "",
        "**By test size** (quartiles of total impressions). Survival of both is "
        f"{pct(s0['share_survive_both'])} in the smallest quartile and "
        f"{pct(s1['share_survive_both'])} in the largest. Size is total traffic, not "
        "traffic per arm.",
        "",
        *_table(sizes, "total impressions"),
        "",
        f"**By number of arms.** Survival of both is {pct(a0['share_survive_both'])} with "
        f"{a0['level']} arms and {pct(a1['share_survive_both'])} with {a1['level']}: each added "
        "arm is one more rival the winner must beat, and each comparison gets less traffic.",
        "",
        *_table(arms, "arms"),
        "",
        "## Method notes",
        "",
        "- Statistics come from `abtest`: `srm.srm_check`, `proportions.chi2_omnibus` and "
        "`two_proportion_ztest`, `power.mde_for_n`, `multiple.within_test`, `adjust` and "
        "`storey_pi0`. Winner counts are checked against `multiple.winner_survival`.",
        "- Flagged = inside the randomization-risk window (dates only; the June 2024 risk "
        "column is not in the OSF files) or SRM p < 0.001 against an equal split.",
        "- MDE uses the test's pooled CTR as baseline, mean impressions per arm, 80% power and "
        "alpha = 0.05 / (k - 1).",
        "- When a test declares more than one winner, the lowest-numbered arm is used.",
        "- A/A pairs are arms in the same test with the same headline and eyecatcher id "
        "(`marts.fct_aa_pairs`); a group of k identical arms gives k(k - 1)/2 pairs.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "analysis" / "output")
    ap.add_argument("--doc", type=Path, default=ROOT / "docs" / "portfolio_findings.md")
    args = ap.parse_args(argv)
    if not (args.out / "portfolio_headline.csv").exists():
        print(f"{args.out}/portfolio_*.csv not found; run `make portfolio` first", file=sys.stderr)
        return 1
    args.doc.parent.mkdir(parents=True, exist_ok=True)
    args.doc.write_text(render(Outputs(args.out)))
    print(f"wrote {args.doc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
